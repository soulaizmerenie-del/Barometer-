"""Сопоставление формулировок задач с текстом сообщений.

Полноценная морфология здесь избыточна, но и обрезки слова по длине мало:
«поиск» и «поиску» должны совпадать, «проектировщика» и «проектирование» —
тоже. Поэтому сначала отсекается окончание, потом слово укорачивается.
"""

from __future__ import annotations

import re

# Окончания в порядке убывания длины: длинные проверяются первыми.
_ENDINGS = (
    "ами", "ями", "ого", "его", "ому", "ему", "ыми", "ими", "ах", "ях",
    "ов", "ев", "ый", "ий", "ое", "ые", "ая", "яя", "ую", "юю", "ою",
    "ей", "ой", "ом", "ем", "ам", "ям", "ся", "ть",
    "а", "я", "о", "е", "ы", "и", "у", "ю", "ь",
)

_STOP = {
    "для", "под", "при", "над", "из", "от", "до", "на", "в", "и", "с", "по",
    "что", "как", "это", "все", "уже", "или", "the", "of",
    "актуальн", "дальнейш", "нужн", "надо",
}


def stem(word: str) -> str:
    """Отсекает окончание и укорачивает основу до сопоставимого вида."""
    word = word.lower().replace("ё", "е")
    for ending in _ENDINGS:
        if len(word) - len(ending) >= 4 and word.endswith(ending):
            word = word[: -len(ending)]
            break
    return word[:6]


def words(text: str) -> set[str]:
    """Значимые основы слов текста."""
    found = {stem(w) for w in re.findall(r"[а-яa-zё]{4,}", text.lower().replace("ё", "е"))}
    return {w for w in found if w not in _STOP and len(w) >= 4}


def relevance(task_title: str, text: str) -> int:
    """Сколько значимых основ задачи встретилось в сообщении."""
    return len(words(task_title) & words(text))
